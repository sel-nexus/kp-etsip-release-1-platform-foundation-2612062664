import { expect, test } from '@playwright/test';

test('leader searches, edits and navigates an assigned application', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  page.on('requestfailed', request => errors.push(`${request.method()} ${request.url()}: ${request.failure()?.errorText}`));
  await page.goto('/login');
  await page.getByLabel('Email').fill('leader@ketsip.local');
  await page.getByLabel('Password', { exact: true }).fill(process.env.E2E_DEMO_PASSWORD || 'DevDemo-Change123!');
  await page.getByRole('button', { name: 'Sign in' }).click();
  await expect(page.getByRole('heading', { name: 'Application Repository' })).toBeVisible();
  await page.getByLabel('Search').fill('no-such-application-e2e-94822');
  await expect(page.getByText('0 applications', { exact: true })).toBeVisible();
  await expect(page.getByText('No applications match these filters.')).toBeVisible();
  await page.getByLabel('Search').fill('Payment Gateway');
  await expect(page.getByRole('link', { name: 'Payment Gateway' })).toBeVisible();
  const downloadPromise = page.waitForEvent('download');
  const exportResponse = page.waitForResponse(response => response.url().includes('/api/reports/applications') && response.url().includes('format=csv'));
  await page.getByRole('button', { name: 'Export CSV' }).click();
  expect((await exportResponse).ok()).toBeTruthy();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toBe('applications.csv');
  const stream = await download.createReadStream();
  let csv = '';
  for await (const chunk of stream) csv += chunk.toString();
  expect(csv).toContain('Payment Gateway');
  expect(csv).not.toContain('Customer Profile');
  await page.getByRole('link', { name: 'Payment Gateway' }).click();
  await expect(page.getByRole('link', { name: 'Payments', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Delete application' })).toHaveCount(0);
  await page.getByRole('link', { name: 'Edit application' }).click();
  await page.getByLabel('Description').fill('Updated through application journey');
  await page.getByRole('button', { name: 'Save application' }).click();
  await expect(page.getByText('Updated through application journey')).toBeVisible();
  await page.getByRole('link', { name: 'Payments', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Payments' })).toBeVisible();
  expect(errors).toEqual([]);
});

test('mobile users can navigate the scoped inventory and reports', async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  page.on('requestfailed', request => errors.push(`${request.method()} ${request.url()}: ${request.failure()?.errorText}`));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/login');
  await page.getByLabel('Email').fill('leader@ketsip.local');
  await page.getByLabel('Password', { exact: true }).fill(process.env.E2E_DEMO_PASSWORD || 'DevDemo-Change123!');
  await page.getByRole('button', { name: 'Sign in' }).click();
  await expect(page.getByRole('heading', { name: 'Application Repository' })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Payment Gateway' })).toBeVisible();
  await page.getByRole('link', { name: 'Reports', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Reports', exact: true })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Payment Gateway' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.screenshot({ path: testInfo.outputPath('reports-mobile.png'), fullPage: true });
  expect(errors).toEqual([]);
});
