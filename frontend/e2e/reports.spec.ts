import { expect, test } from '@playwright/test';

 test('leader views scoped reports and downloads filtered inventory', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  page.on('requestfailed', request => errors.push(`${request.method()} ${request.url()}: ${request.failure()?.errorText}`));
  await page.goto('/login');
  await page.getByLabel('Email').fill('leader@ketsip.local');
  await page.getByLabel('Password', { exact: true }).fill(process.env.E2E_DEMO_PASSWORD || 'DevDemo-Change123!');
  await page.getByRole('button', { name: 'Sign in' }).click();
  await expect(page.getByRole('link', { name: 'Payment Gateway' })).toBeVisible();
  let release!: () => void;
  const held = new Promise<void>(resolve => { release = resolve; });
  let received!: () => void;
  const responseReady = new Promise<void>(resolve => { received = resolve; });
  await page.route('**/api/reports/applications*', async route => {
    const response = await route.fetch();
    received();
    await held;
    await route.fulfill({ response });
  });
  await page.getByRole('link', { name: 'Reports', exact: true }).click();
  await responseReady;
  try {
    await expect(page.getByRole('status')).toHaveText('Loading report…');
    await expect(page.getByRole('link', { name: 'Payment Gateway' })).toHaveCount(0);
  } finally { release(); }
  await expect(page.getByText('Loading report…')).toHaveCount(0);
  await expect(page.getByRole('link', { name: 'Payment Gateway' })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Customer Profile' })).toHaveCount(0);
  await page.getByLabel('Risk level').selectOption('High');
  await expect(page.getByText('1 matching records')).toBeVisible();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export CSV' }).click();
  const download = await downloadPromise;
  const stream = await download.createReadStream();
  let csv = '';
  for await (const chunk of stream) csv += chunk.toString();
  expect(csv).toContain('name,portfolioName,criticality');
  expect(csv).toContain('Payment Gateway');
  expect(csv).not.toContain('Billing');
  expect(csv).not.toContain('Settlement');
  expect(csv).not.toContain('Customer Profile');
  await page.getByRole('link', { name: 'Payment Gateway' }).click();
  await expect(page.getByRole('heading', { name: 'Payment Gateway' })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Payments', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Reports', exact: true }).click();
  await page.getByLabel('Report', { exact: true }).selectOption('portfolios');
  await expect(page.getByRole('link', { name: 'Payments', exact: true })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Customer Platform', exact: true })).toHaveCount(0);
  const portfolioExport = page.waitForResponse(response => new URL(response.url()).pathname === '/api/reports/portfolios' && new URL(response.url()).searchParams.get('format') === 'csv');
  const portfolioDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export CSV' }).click();
  expect((await portfolioExport).ok()).toBeTruthy();
  const portfolioFile = await portfolioDownload;
  expect(portfolioFile.suggestedFilename()).toBe('portfolios.csv');
  const portfolioStream = await portfolioFile.createReadStream();
  let portfolioCsv = '';
  for await (const chunk of portfolioStream) portfolioCsv += chunk.toString();
  expect(portfolioCsv).toContain('name,owner,productArea,applicationCount,qualityScore,status');
  expect(portfolioCsv).toContain('Payments,Payments Team,Payments,3,');
  expect(portfolioCsv).not.toContain('Customer Platform');
  expect(portfolioCsv).not.toContain('Data & Analytics');
  expect(errors).toEqual([]);
});

