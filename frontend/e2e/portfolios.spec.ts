import { expect, test } from '@playwright/test';

test('leader views and edits an assigned portfolio through the live API', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  page.on('requestfailed', request => errors.push(`${request.method()} ${request.url()}: ${request.failure()?.errorText}`));
  const password = process.env.E2E_DEMO_PASSWORD || 'DevDemo-Change123!';
  await page.goto('/login');
  await page.getByLabel('Email').fill('leader@ketsip.local');
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Sign in' }).click();
  await page.getByRole('link', { name: 'Portfolios', exact: true }).click();
  await expect(page.getByRole('link', { name: 'Payments', exact: true })).toBeVisible();
  await page.getByLabel('Search').fill('Payments');
  await page.getByRole('link', { name: 'Payments', exact: true }).click();
  await expect(page.getByRole('link', { name: 'Payment Gateway' })).toBeVisible();
  await expect(page.getByText('76', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Delete portfolio' })).toHaveCount(0);
  await page.getByRole('link', { name: 'Edit portfolio' }).click();
  await page.getByLabel('Description').fill('Updated through the portfolio journey');
  await page.getByRole('button', { name: 'Save portfolio' }).click();
  await expect(page.getByText('Updated through the portfolio journey')).toBeVisible();
  await page.getByRole('link', { name: 'Payment Gateway' }).click();
  await expect(page.getByRole('heading', { name: 'Payment Gateway' })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Payments', exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});

test('administrator manages linked portfolio and application records', async ({ page }) => {
  test.setTimeout(120_000);
  const errors: string[] = [];
  // Only the expected conflict's Chromium resource error is excluded; transport failures are never excluded.
  let conflictUrl = '';
  let expectingConflict = false;
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => {
    if (message.type() !== 'error') return;
    if (expectingConflict && message.location().url === conflictUrl && /^Failed to load resource: the server responded with a status of 409(?: \(Conflict\))?$/.test(message.text())) return;
    errors.push(message.text());
  });
  page.on('requestfailed', request => errors.push(`${request.method()} ${request.url()}: ${request.failure()?.errorText}`));
  const password = process.env.E2E_ADMIN_PASSWORD;
  if (!password) throw new Error('Set E2E_ADMIN_PASSWORD for a fresh disposable database');
  const suffix = `${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
  const portfolio = `E2E Portfolio ${suffix}`;
  const application = `E2E Application ${suffix}`;
  await page.goto('/login');
  await page.getByLabel('Email').fill('admin@ketsip.local');
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Sign in' }).click();
  await page.getByRole('link', { name: 'Portfolios', exact: true }).click();
  await page.getByRole('link', { name: 'Create portfolio' }).click();
  await page.getByLabel('Name', { exact: true }).fill(portfolio);
  await page.getByLabel('Owner', { exact: true }).fill('E2E owner');
  await page.getByLabel('Description').fill('Original portfolio description');
  const createdPortfolio = page.waitForResponse(response => new URL(response.url()).pathname === '/api/portfolios' && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Save portfolio' }).click();
  expect((await createdPortfolio).status()).toBe(201);
  await expect(page.getByRole('heading', { name: portfolio })).toBeVisible();
  await expect(page.getByText('No linked applications.')).toBeVisible();
  await page.getByRole('link', { name: 'Edit portfolio' }).click();
  await page.getByLabel('Description').fill('Edited portfolio description');
  await page.getByRole('button', { name: 'Save portfolio' }).click();
  await expect(page.getByText('Edited portfolio description')).toBeVisible();
  await page.reload();
  await expect(page.getByText('Edited portfolio description')).toBeVisible();
  const portfolioUrl = page.url();
  const portfolioId = new URL(portfolioUrl).pathname.split('/').pop();

  await page.getByRole('link', { name: 'Applications', exact: true }).click();
  await page.getByRole('link', { name: 'Create application' }).click();
  await page.getByLabel('Name', { exact: true }).fill(application);
  await page.getByLabel('Description').fill('Original application description');
  await page.getByLabel('Portfolio', { exact: true }).selectOption({ label: portfolio });
  await page.getByLabel('Quality score').fill('73');
  const createdApplication = page.waitForResponse(response => new URL(response.url()).pathname === '/api/applications' && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Save application' }).click();
  expect((await createdApplication).status()).toBe(201);
  await expect(page.getByRole('heading', { name: application })).toBeVisible();
  await expect(page.getByRole('link', { name: portfolio, exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Edit application' }).click();
  await page.getByLabel('Description').fill('Edited application description');
  await page.getByRole('button', { name: 'Save application' }).click();
  await expect(page.getByText('Edited application description')).toBeVisible();
  await page.reload();
  await expect(page.getByText('Edited application description')).toBeVisible();
  await page.getByRole('link', { name: portfolio, exact: true }).click();
  await expect(page.getByRole('link', { name: application, exact: true })).toBeVisible();
  await expect(page.getByText('73', { exact: true }).first()).toBeVisible();

  conflictUrl = new URL(`/api/portfolios/${portfolioId}`, page.url()).href;
  expectingConflict = true;
  const conflict = page.waitForResponse(response => response.url() === conflictUrl && response.request().method() === 'DELETE');
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Delete portfolio' }).click();
  expect((await conflict).status()).toBe(409);
  await expect(page.getByRole('alert')).toHaveText('Portfolio contains applications');
  expectingConflict = false;
  await expect(page.getByRole('heading', { name: portfolio })).toBeVisible();
  await page.getByRole('link', { name: application, exact: true }).click();
  await expect(page.getByRole('heading', { name: application })).toBeVisible();
  await expect(page.getByText('Edited application description')).toBeVisible();
  const deletedApplication = page.waitForResponse(response => /^\/api\/applications\/[^/]+$/.test(new URL(response.url()).pathname) && response.request().method() === 'DELETE');
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Delete application' }).click();
  expect((await deletedApplication).status()).toBe(204);
  await expect(page.getByRole('heading', { name: 'Application Repository' })).toBeVisible();
  await page.getByLabel('Search').fill(application);
  await expect(page.getByText('No applications match these filters.')).toBeVisible();
  await page.getByRole('link', { name: 'Portfolios', exact: true }).click();
  await page.getByLabel('Search').fill(portfolio);
  await page.getByRole('link', { name: portfolio, exact: true }).click();
  await expect(page.getByText('No linked applications.')).toBeVisible();
  const deletedPortfolio = page.waitForResponse(response => response.url() === conflictUrl && response.request().method() === 'DELETE');
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Delete portfolio' }).click();
  expect((await deletedPortfolio).status()).toBe(204);
  await expect(page.getByRole('heading', { name: 'Portfolios' })).toBeVisible();
  await page.getByLabel('Search').fill(portfolio);
  await expect(page.getByText('No portfolios match these filters.')).toBeVisible();
  expect(errors).toEqual([]);
});
