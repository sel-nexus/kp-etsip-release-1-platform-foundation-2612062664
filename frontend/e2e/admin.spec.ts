import { test, expect } from '@playwright/test';

test('administrator manages an account and auditor reviews its history', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  page.on('requestfailed', request => errors.push(`${request.method()} ${request.url()}: ${request.failure()?.errorText}`));
  const password = process.env.E2E_ADMIN_PASSWORD;
  if (!password) throw new Error('Set E2E_ADMIN_PASSWORD for a fresh disposable database');
  const replacement = `Changed-Admin-${Date.now()}!`;
  const email = `admin-journey-${Date.now()}@example.com`;
  await page.goto('/login');
  await page.getByLabel('Email').fill('admin@ketsip.local');
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Sign in' }).click();
  // The auth journey restores the seed password; create a separate first-login admin.
  await page.getByRole('link', { name: 'Administration' }).click();
  const newAdminEmail = `first-admin-${Date.now()}@example.com`;
  await page.getByLabel('Name', { exact: true }).fill('Journey Administrator');
  await page.getByLabel('Email', { exact: true }).fill(newAdminEmail);
  await page.getByLabel('Initial password').fill(password);
  await page.getByLabel('Role', { exact: true }).selectOption('Administrator');
  await page.getByRole('button', { name: 'Save user' }).click();
  await expect(page.getByText('User saved.')).toBeVisible();
  await expect(page.getByText(newAdminEmail)).toBeVisible();
  await page.getByRole('button', { name: 'Sign out' }).click();
  await page.getByLabel('Email').fill(newAdminEmail);
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Sign in' }).click();
  await expect(page.getByLabel('Current password')).toBeVisible();
  await page.getByLabel('Current password').fill(password);
  await page.getByLabel('New password').fill(replacement);
  await page.getByRole('button', { name: 'Change password' }).click();
  await page.getByRole('link', { name: 'Administration' }).click();
  await page.getByRole('button', { name: 'Roles', exact: true }).click();
  await page.getByRole('button', { name: 'Edit Read Only' }).click();
  await expect(page.getByLabel('export', { exact: true })).not.toBeChecked();
  await page.getByLabel('export', { exact: true }).check();
  const roleUpdate = page.waitForResponse(response => /\/api\/roles\/[^/?]+$/.test(response.url()) && response.request().method() === 'PUT');
  await page.getByRole('button', { name: 'Save role' }).click();
  expect((await roleUpdate).ok()).toBeTruthy();
  await expect(page.getByText('Role saved.')).toBeVisible();
  await page.getByRole('link', { name: 'Dashboard', exact: true }).click();
  await page.getByRole('link', { name: 'Administration' }).click();
  await page.getByRole('button', { name: 'Roles', exact: true }).click();
  await page.getByRole('button', { name: 'Edit Read Only' }).click();
  await expect(page.getByLabel('export', { exact: true })).toBeChecked();
  await page.getByLabel('export', { exact: true }).uncheck();
  const restoreRole = page.waitForResponse(response => /\/api\/roles\/[^/?]+$/.test(response.url()) && response.request().method() === 'PUT');
  await page.getByRole('button', { name: 'Save role' }).click();
  expect((await restoreRole).ok()).toBeTruthy();
  await expect(page.getByText('Role saved.')).toBeVisible();
  await page.getByRole('button', { name: 'Users', exact: true }).click();
  await page.getByLabel('Name', { exact: true }).fill('Journey Engineer');
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByLabel('Initial password').fill('Journey-Password-12345!');
  await page.getByLabel('Payments', { exact: true }).check();
  await page.getByRole('button', { name: 'Save user' }).click();
  await expect(page.getByText('User saved.')).toBeVisible();
  await expect(page.getByText(email)).toBeVisible();
  await page.getByRole('button', { name: 'Edit Journey Engineer' }).click();
  await page.getByLabel('Role', { exact: true }).selectOption('Read Only');
  await page.getByRole('button', { name: 'Save user' }).click();
  await expect(page.getByRole('row').filter({ hasText: email })).toContainText('Read Only');
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Deactivate Journey Engineer' }).click();
  await expect(page.getByRole('row').filter({ hasText: email })).toContainText('Inactive');
  await page.getByRole('link', { name: 'Audit log' }).click();
  await page.getByLabel('Action').selectOption('roleChange');
  await page.getByRole('button', { name: 'Apply filters' }).click();
  await expect(page.getByText('User role changed')).toBeVisible();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export current page CSV' }).click();
  expect((await download).suggestedFilename()).toBe('audit-logs.csv');
  await page.getByRole('button', { name: 'Sign out' }).click();
  await page.getByLabel('Email').fill('auditor@ketsip.local');
  await page.getByLabel('Password', { exact: true }).fill(process.env.E2E_DEMO_PASSWORD || 'DevDemo-Change123!');
  await page.getByRole('button', { name: 'Sign in' }).click();
  await page.getByRole('link', { name: 'Audit log' }).click();
  await expect(page.getByText('User role changed')).toBeVisible();
  await expect(page.getByRole('link', { name: 'Administration' })).toHaveCount(0);
  expect(errors).toEqual([]);
});
